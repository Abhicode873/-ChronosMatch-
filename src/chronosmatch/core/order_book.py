
"""Price-time priority limit order book for ChronosMatch."""

import heapq
from collections import deque
from dataclasses import dataclass

from .models import Order, Side


@dataclass(frozen=True, slots=True)
class Trade:
    """An executed trade between a resting order and an incoming order."""

    symbol: str
    maker_order_id: str
    taker_order_id: str
    price_ticks: int
    quantity: int


@dataclass(slots=True)
class _RestingOrder:
    """Mutable internal state for an order resting in the book."""

    order: Order
    remaining_quantity: int


class OrderBook:
    """A single-symbol limit order book with price-time priority.

    Buy orders are prioritized by highest price first.
    Sell orders are prioritized by lowest price first.
    Orders at the same price are matched in submission order (FIFO).

    The resting order determines the execution price. This class is a
    correctness-focused Python reference implementation, not yet the
    optimized Cython matching engine.
    """

    def __init__(self, symbol: str) -> None:
        if not isinstance(symbol, str):
            raise TypeError("symbol must be a string")

        normalized_symbol = symbol.strip().upper()
        if not normalized_symbol:
            raise ValueError("symbol must not be empty")

        self.symbol = normalized_symbol

        # Price -> FIFO queue of resting orders.
        self._bids: dict[int, deque[_RestingOrder]] = {}
        self._asks: dict[int, deque[_RestingOrder]] = {}

        # Negative bid prices make heapq return the highest bid first.
        self._bid_prices: list[int] = []
        self._ask_prices: list[int] = []

        # Contains currently resting orders only.
        self._active_orders: dict[str, _RestingOrder] = {}

        # Prevent reuse of order IDs during this book's lifetime.
        self._seen_order_ids: set[str] = set()

    @property
    def best_bid(self) -> int | None:
        """Return the highest resting buy price, if one exists."""
        return self._peek_best_price(Side.BUY)

    @property
    def best_ask(self) -> int | None:
        """Return the lowest resting sell price, if one exists."""
        return self._peek_best_price(Side.SELL)

    @property
    def active_order_count(self) -> int:
        """Return the number of orders currently resting in the book."""
        return len(self._active_orders)

    def cancel(self, order_id: str) -> bool:
        """Cancel an active order and remove its remaining quantity.

        Returns True if an active order was cancelled, or False if the
        order is unknown, already cancelled, or fully filled.
        Cancelled order IDs remain reserved and cannot be reused.
        """
        if not isinstance(order_id, str):
            raise TypeError("order_id must be a string")

        resting = self._active_orders.get(order_id)
        if resting is None:
            return False

        order = resting.order

        # Find the price level containing this order.
        levels = self._bids if order.side is Side.BUY else self._asks
        price_ticks = order.price_ticks
        queue = levels[price_ticks]

        # Remove only this order; preserve the order of all others.
        queue.remove(resting)
        del self._active_orders[order_id]

        # The corresponding heap entry, if any, becomes stale.
        # _peek_best_price() already discards stale entries lazily.
        if not queue:
            del levels[price_ticks]

        # Do not remove the ID from _seen_order_ids.
        return True


    def submit(self, order: Order) -> list[Trade]:
        """Submit an order, execute compatible trades, and rest any remainder.

        Returns trades generated by this submission, in execution order.
        Invalid orders are rejected before the book is modified.
        """
        if not isinstance(order, Order):
            raise TypeError("order must be an Order instance")

        if order.symbol != self.symbol:
            raise ValueError(
                f"Order symbol {order.symbol!r} does not match "
                f"book symbol {self.symbol!r}"
            )

        if order.order_id in self._seen_order_ids:
            raise ValueError(f"Duplicate order ID: {order.order_id!r}")

        self._seen_order_ids.add(order.order_id)

        remaining = order.quantity
        trades: list[Trade] = []

        if order.side is Side.BUY:
            remaining = self._match_buy(order, remaining, trades)
        else:
            remaining = self._match_sell(order, remaining, trades)

        if remaining > 0:
            self._add_resting_order(order, remaining)

        return trades

    def _match_buy(
        self,
        incoming: Order,
        remaining: int,
        trades: list[Trade],
    ) -> int:
        """Match an incoming buy against the cheapest eligible asks."""
        while remaining > 0:
            ask_price = self.best_ask

            if ask_price is None or ask_price > incoming.price_ticks:
                break

            resting = self._asks[ask_price][0]
            quantity = min(remaining, resting.remaining_quantity)

            trades.append(
                Trade(
                    symbol=self.symbol,
                    maker_order_id=resting.order.order_id,
                    taker_order_id=incoming.order_id,
                    price_ticks=resting.order.price_ticks,
                    quantity=quantity,
                )
            )

            remaining -= quantity
            resting.remaining_quantity -= quantity

            if resting.remaining_quantity == 0:
                self._remove_filled_order(Side.SELL, ask_price)

        return remaining

    def _match_sell(
        self,
        incoming: Order,
        remaining: int,
        trades: list[Trade],
    ) -> int:
        """Match an incoming sell against the highest eligible bids."""
        while remaining > 0:
            bid_price = self.best_bid

            if bid_price is None or bid_price < incoming.price_ticks:
                break

            resting = self._bids[bid_price][0]
            quantity = min(remaining, resting.remaining_quantity)

            trades.append(
                Trade(
                    symbol=self.symbol,
                    maker_order_id=resting.order.order_id,
                    taker_order_id=incoming.order_id,
                    price_ticks=resting.order.price_ticks,
                    quantity=quantity,
                )
            )

            remaining -= quantity
            resting.remaining_quantity -= quantity

            if resting.remaining_quantity == 0:
                self._remove_filled_order(Side.BUY, bid_price)

        return remaining

    def _add_resting_order(self, order: Order, quantity: int) -> None:
        """Add an unfilled order remainder to the appropriate price level."""
        resting = _RestingOrder(
            order=order,
            remaining_quantity=quantity,
        )

        if order.side is Side.BUY:
            levels = self._bids
            heap = self._bid_prices
            heap_price = -order.price_ticks
        else:
            levels = self._asks
            heap = self._ask_prices
            heap_price = order.price_ticks

        if order.price_ticks not in levels:
            levels[order.price_ticks] = deque()
            heapq.heappush(heap, heap_price)

        # Appending preserves FIFO priority at this price level.
        levels[order.price_ticks].append(resting)
        self._active_orders[order.order_id] = resting

    def _remove_filled_order(self, side: Side, price_ticks: int) -> None:
        """Remove the fully filled front order from its price level."""
        levels = self._asks if side is Side.SELL else self._bids
        queue = levels[price_ticks]
        filled = queue.popleft()

        del self._active_orders[filled.order.order_id]

        if not queue:
            del levels[price_ticks]
            # Its heap entry becomes stale and is removed lazily.

    def _peek_best_price(self, side: Side) -> int | None:
        """Return the best valid price while discarding stale heap entries."""
        if side is Side.BUY:
            heap = self._bid_prices
            levels = self._bids

            while heap:
                price = -heap[0]
                if levels.get(price):
                    return price
                heapq.heappop(heap)

        else:
            heap = self._ask_prices
            levels = self._asks

            while heap:
                price = heap[0]
                if levels.get(price):
                    return price
                heapq.heappop(heap)

        return None
