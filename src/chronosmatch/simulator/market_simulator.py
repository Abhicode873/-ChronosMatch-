
"""Asynchronous market order simulator for ChronosMatch."""

import asyncio
import random
import time
from collections.abc import AsyncIterator, Mapping

from chronosmatch.core.models import Order, Side

_DEFAULT_BASE_PRICES = {
    "AAPL": 100_000,
    "MSFT": 400_000,
    "GOOGL": 150_000,
}


class AsyncMarketSimulator:
    """Generate reproducible simulated limit orders asynchronously."""

    def __init__(
        self,
        base_prices: Mapping[str, int] | None = None,
        *,
        seed: int | None = None,
        min_quantity: int = 1,
        max_quantity: int = 10,
        price_variation_ticks: int = 5,
        interval_seconds: float = 0.0,
    ) -> None:
        if base_prices is None:
            base_prices = _DEFAULT_BASE_PRICES

        if not isinstance(base_prices, Mapping) or not base_prices:
            raise ValueError("base_prices must be a non-empty mapping")

        normalized_prices: dict[str, int] = {}

        for symbol, price in base_prices.items():
            if not isinstance(symbol, str):
                raise TypeError("Symbols must be strings")

            normalized_symbol = symbol.strip().upper()

            if not normalized_symbol:
                raise ValueError("Symbols must not be empty")

            if normalized_symbol in normalized_prices:
                raise ValueError("Duplicate symbols are not allowed")

            if type(price) is not int:
                raise TypeError("Base prices must be integers")

            if price <= 0:
                raise ValueError("Base prices must be positive")

            normalized_prices[normalized_symbol] = price

        if type(min_quantity) is not int:
            raise TypeError("min_quantity must be an integer")

        if type(max_quantity) is not int:
            raise TypeError("max_quantity must be an integer")

        if min_quantity <= 0 or max_quantity < min_quantity:
            raise ValueError("Invalid quantity range")

        if type(price_variation_ticks) is not int:
            raise TypeError("price_variation_ticks must be an integer")

        if price_variation_ticks < 0:
            raise ValueError("price_variation_ticks cannot be negative")

        if any(
            price - price_variation_ticks <= 0
            for price in normalized_prices.values()
        ):
            raise ValueError(
                "Price variation would create a non-positive price"
            )

        if isinstance(interval_seconds, bool) or not isinstance(
            interval_seconds, (int, float)
        ):
            raise TypeError("interval_seconds must be a number")

        if interval_seconds < 0 or not float(interval_seconds) < float("inf"):
            raise ValueError(
                "interval_seconds must be finite and non-negative"
            )

        if seed is not None and type(seed) is not int:
            raise TypeError("seed must be an integer or None")

        self._base_prices = normalized_prices
        self._symbols = tuple(normalized_prices)
        self._min_quantity = min_quantity
        self._max_quantity = max_quantity
        self._price_variation_ticks = price_variation_ticks
        self._interval_seconds = float(interval_seconds)

        self._rng = random.Random(seed)
        self._sequence = 0

    @property
    def generated_count(self) -> int:
        """Return the total number of orders generated by this instance."""
        return self._sequence

    async def stream_orders(self, count: int) -> AsyncIterator[Order]:
        """Yield a finite number of simulated orders asynchronously."""
        if type(count) is not int:
            raise TypeError("count must be an integer")

        if count <= 0:
            raise ValueError("count must be greater than zero")

        for index in range(count):
            self._sequence += 1

            symbol = self._rng.choice(self._symbols)
            side = self._rng.choice((Side.BUY, Side.SELL))

            base_price = self._base_prices[symbol]
            price_offset = self._rng.randint(
                -self._price_variation_ticks,
                self._price_variation_ticks,
            )

            order = Order(
                order_id=f"SIM-{self._sequence:012d}",
                symbol=symbol,
                side=side,
                price_ticks=base_price + price_offset,
                quantity=self._rng.randint(
                    self._min_quantity,
                    self._max_quantity,
                ),
                timestamp_ns=time.monotonic_ns(),
            )

            yield order

            # Yield control to other asyncio tasks between orders.
            if index < count - 1:
                await asyncio.sleep(self._interval_seconds)
