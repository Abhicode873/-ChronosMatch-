
import { useMemo, useState } from 'react'
import {
  Search,
  ArrowLeftRight,
  Activity,
  TrendingUp,
} from 'lucide-react'
import type { SimulationResponse } from '../../services/api'

const STORAGE_KEY = 'chronosmatch_latest_simulation'

function loadLatestSimulation(): SimulationResponse | null {
  try {
    const stored = sessionStorage.getItem(STORAGE_KEY)

    return stored
      ? (JSON.parse(stored) as SimulationResponse)
      : null
  } catch {
    sessionStorage.removeItem(STORAGE_KEY)
    return null
  }
}

export default function TradeHistory() {
  const [simulation] = useState<SimulationResponse | null>(
    loadLatestSimulation,
  )
  const [search, setSearch] = useState('')
  const [symbol, setSymbol] = useState('ALL')

  const trades = useMemo(
    () => simulation?.trades ?? [],
    [simulation],
  )

  const filteredTrades = useMemo(() => {
    return trades.filter((trade) => {
      const searchTerm = search.toLowerCase()

      const matchesSearch =
        trade.maker_order_id.toLowerCase().includes(searchTerm) ||
        trade.taker_order_id.toLowerCase().includes(searchTerm) ||
        trade.symbol.toLowerCase().includes(searchTerm)

      const matchesSymbol =
        symbol === 'ALL' || trade.symbol === symbol

      return matchesSearch && matchesSymbol
    })
  }, [trades, search, symbol])

  const totalQuantity = trades.reduce(
    (total, trade) => total + trade.quantity,
    0,
  )

  const symbols = [...new Set(trades.map((trade) => trade.symbol))]

  const averageQuantity =
    trades.length > 0 ? totalQuantity / trades.length : 0

  if (!simulation) {
    return (
      <div className="space-y-6">
        <div className="flex items-center gap-2">
          <ArrowLeftRight size={22} className="text-blue-500" />
          <h3 className="text-xl font-bold text-[var(--foreground)]">
            Trade History
          </h3>
        </div>

        <div className="rounded-2xl border border-[var(--border)] bg-[var(--surface)] p-8 text-center">
          <Activity size={32} className="mx-auto text-[var(--muted)]" />

          <h4 className="mt-3 font-semibold text-[var(--foreground)]">
            No trade records available
          </h4>

          <p className="mt-2 text-sm text-[var(--muted)]">
            Run a simulation first to view backend-generated trade records.
          </p>
        </div>
      </div>
    )
  }

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div>
          <div className="flex items-center gap-2">
            <ArrowLeftRight size={22} className="text-blue-500" />

            <h3 className="text-xl font-bold text-[var(--foreground)]">
              Trade History
            </h3>
          </div>

          <p className="mt-1 text-sm text-[var(--muted)]">
            Review executed trades generated by the Python matching engine.
          </p>
        </div>

        <span className="rounded-lg border border-emerald-500/30 bg-emerald-500/10 px-3 py-2 text-xs font-medium text-emerald-500">
          BACKEND DATA
        </span>
      </div>

      {/* Summary cards */}
      <div className="grid grid-cols-1 gap-4 sm:grid-cols-3">
        <div className="rounded-2xl border border-[var(--border)] bg-[var(--surface)] p-5">
          <Activity className="text-blue-500" size={21} />

          <p className="mt-3 text-sm text-[var(--muted)]">
            Total Executions
          </p>

          <h4 className="mt-1 text-2xl font-bold text-[var(--foreground)]">
            {trades.length.toLocaleString()}
          </h4>
        </div>

        <div className="rounded-2xl border border-[var(--border)] bg-[var(--surface)] p-5">
          <ArrowLeftRight className="text-emerald-500" size={21} />

          <p className="mt-3 text-sm text-[var(--muted)]">
            Total Executed Quantity
          </p>

          <h4 className="mt-1 text-2xl font-bold text-emerald-500">
            {totalQuantity.toLocaleString()}
          </h4>
        </div>

        <div className="rounded-2xl border border-[var(--border)] bg-[var(--surface)] p-5">
          <TrendingUp className="text-purple-500" size={21} />

          <p className="mt-3 text-sm text-[var(--muted)]">
            Average Trade Quantity
          </p>

          <h4 className="mt-1 text-2xl font-bold text-[var(--foreground)]">
            {averageQuantity.toFixed(2)}
          </h4>
        </div>
      </div>

      {/* Quantity summary */}
      <div className="rounded-2xl border border-[var(--border)] bg-[var(--surface)] p-5">
        <p className="text-sm text-[var(--muted)]">
          Total executed quantity
        </p>

        <h4 className="mt-2 text-2xl font-bold text-[var(--foreground)]">
          {totalQuantity.toLocaleString()} units
        </h4>

        <p className="mt-1 text-xs text-[var(--muted)]">
          Calculated from actual backend trade records.
        </p>
      </div>

      {/* Trade table */}
      <div className="overflow-hidden rounded-2xl border border-[var(--border)] bg-[var(--surface)]">
        <div className="flex flex-wrap items-center justify-between gap-4 border-b border-[var(--border)] p-5">
          <div>
            <h4 className="font-semibold text-[var(--foreground)]">
              Execution Records
            </h4>

            <p className="mt-1 text-xs text-[var(--muted)]">
              Search and filter backend-generated executions.
            </p>
          </div>

          <span className="text-xs text-[var(--muted)]">
            {filteredTrades.length.toLocaleString()} records found
          </span>
        </div>

        {/* Filters */}
        <div className="flex flex-col gap-3 border-b border-[var(--border)] p-5 sm:flex-row">
          <div className="relative flex-1">
            <Search
              size={17}
              className="absolute left-3 top-1/2 -translate-y-1/2 text-[var(--muted)]"
            />

            <input
              value={search}
              onChange={(event) => setSearch(event.target.value)}
              placeholder="Search maker ID, taker ID or symbol..."
              className="w-full rounded-xl border border-[var(--border)] bg-[var(--surface-secondary)] py-3 pl-10 pr-4 text-sm text-[var(--foreground)] outline-none focus:border-blue-500"
            />
          </div>

          <select
            value={symbol}
            onChange={(event) => setSymbol(event.target.value)}
            className="rounded-xl border border-[var(--border)] bg-[var(--surface-secondary)] px-4 py-3 text-sm text-[var(--foreground)] outline-none"
          >
            <option value="ALL">All Symbols</option>

            {symbols.map((item) => (
              <option key={item} value={item}>
                {item}
              </option>
            ))}
          </select>
        </div>

        {/* Table */}
        <div className="overflow-x-auto">
          <table className="w-full text-left text-sm">
            <thead className="bg-[var(--surface-secondary)] text-xs text-[var(--muted)]">
              <tr>
                <th className="px-5 py-4">MAKER ORDER ID</th>
                <th className="px-5 py-4">TAKER ORDER ID</th>
                <th className="px-5 py-4">SYMBOL</th>
                <th className="px-5 py-4">PRICE (TICKS)</th>
                <th className="px-5 py-4">QUANTITY</th>
              </tr>
            </thead>

            <tbody>
              {filteredTrades.map((trade, index) => (
                <tr
                  key={`${trade.maker_order_id}-${trade.taker_order_id}-${index}`}
                  className="border-t border-[var(--border)] transition hover:bg-[var(--surface-secondary)]"
                >
                  <td className="whitespace-nowrap px-5 py-4 font-semibold text-[var(--foreground)]">
                    {trade.maker_order_id}
                  </td>

                  <td className="whitespace-nowrap px-5 py-4 font-semibold text-[var(--foreground)]">
                    {trade.taker_order_id}
                  </td>

                  <td className="px-5 py-4 font-semibold text-[var(--foreground)]">
                    {trade.symbol}
                  </td>

                  <td className="px-5 py-4 font-medium text-[var(--foreground)]">
                    {trade.price_ticks.toLocaleString()}
                  </td>

                  <td className="px-5 py-4 text-[var(--foreground)]">
                    {trade.quantity.toLocaleString()}
                  </td>
                </tr>
              ))}

              {filteredTrades.length === 0 && (
                <tr>
                  <td
                    colSpan={5}
                    className="px-5 py-12 text-center text-[var(--muted)]"
                  >
                    No matching trade records found.
                  </td>
                </tr>
              )}
            </tbody>
          </table>
        </div>
      </div>
    </div>
  )
}
